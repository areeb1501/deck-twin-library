// STD = Sch 40 to NPS 10, then 9.53. XS = Sch 80 to NPS 8, then 12.70. 40S/80S per B36.19M (to NPS 24).
for (const [k, [, w]] of Object.entries(PIPE)) {
  const nps = Number(k)
  w.STD ??= nps <= 10 ? w['40'] : 9.53
  w.XS ??= nps <= 8 ? w['80'] : 12.7
  if (nps <= 24) {
    w['40S'] ??= nps <= 10 ? w['40'] : 9.53
    w['80S'] ??= nps <= 8 ? w['80'] : 12.7
  }
}

export const NPS_SIZES: readonly number[] = tableKeys(PIPE)

// Nominal light-to-heavy order, used only to pick a fallback when a schedule is not defined for a size.
const RANK: readonly Schedule[] = [
  '5S', '10S', '10', '20', '30', '40S', 'STD', '40', '60', '80S', 'XS', '80', '100', '120', '140', '160', 'XXS',
]

function row(nps: number) {
  return PIPE[nearest(NPS_SIZES, nps)]
}

export function pipeOD(nps: number): number {
  return mm(row(nps)[0])
}

export function pipeWall(nps: number, schedule: Schedule = 'STD'): number {
  const w = row(nps)[1]
  const exact = w[schedule]
  if (exact !== undefined) return mm(exact)
  // Lightest defined wall at least as heavy as every defined schedule ranked below the request, else the heaviest.
  const defined = (list: readonly Schedule[]) => list.map((s) => w[s]).filter((v): v is number => v !== undefined)
  const all = defined(RANK)
  if (!all.length) return mm(9.53)
  const floor = Math.max(0, ...defined(RANK.slice(0, Math.max(0, RANK.indexOf(schedule)))))
  const heavier = all.filter((v) => v >= floor)
  return mm(heavier.length ? Math.min(...heavier) : Math.max(...all))
}

export function pipeID(nps: number, schedule: Schedule = 'STD'): number {
  return pipeOD(nps) - 2 * pipeWall(nps, schedule)
}

/** kg/m, carbon steel at 7850 kg/m3 (plain end). */
export function pipeMass(nps: number, schedule: Schedule = 'STD'): number {
  const d = pipeOD(nps)
  const t = pipeWall(nps, schedule)
  return Math.PI * (d - t) * t * 7850
}

