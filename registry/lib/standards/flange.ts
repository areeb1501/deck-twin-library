const SIZES = tableKeys(RF_DIA)

function hasSize(r: Rating, nps: number): boolean {
  return nps <= 24 ? B165[r][nps] !== undefined : B1647A[r]?.[nps] !== undefined
}

/** Snap to a flange size, then to the nearest class that defines it (ties go to the higher class). */
function resolve(nps: number, rating: Rating): [number, Rating] {
  const size = nearest(SIZES, nps)
  const r: Rating = RATINGS.includes(rating) ? rating : 300
  if (hasSize(r, size)) return [size, r]
  const i = RATINGS.indexOf(r)
  for (let d = 1; d < RATINGS.length; d++) {
    for (const j of [i + d, i - d]) {
      const c = RATINGS[j]
      if (c !== undefined && hasSize(c, size)) return [size, c]
    }
  }
  return [size, 300]
}

const rfHeightIn = (r: Rating) => (r <= 300 ? 0.0625 : 0.25)

/**
 * Weld-neck RF flange. `thickness` and `hubLength` exclude the raised face for every class
 * (the 1.6 mm RF that B16.5 folds into tf and Y for 150/300 is subtracted), so the face sits
 * `raisedFaceHeight` proud of `thickness`, and weld end to face = hubLength + raisedFaceHeight.
 */
export function flange(nps: number, rating: Rating = 300): FlangeDims {
  const [size, r] = resolve(nps, rating)
  const inRf = r <= 300 ? 0.0625 : 0
  let o: number, tf: number, x: number, y: number, bc: number, n: number, bd: number
  if (size <= 24) {
    ;[o, tf, x, y, bc, n, bd] = B165[r][size]
  } else {
    const a = (B1647A[r] ?? B1647A[900]!)[size]
    const h = HUB_A[r] ?? HUB_A[900]!
    ;[o, tf, bc, n, bd] = a
    x = pipeOD(size) / 0.0254 + h.dx
    y = h.y24 + h.slope * (size - 24)
  }
  return {
    od: inch(o),
    thickness: inch(tf - inRf),
    raisedFace: inch(RF_DIA[size]),
    raisedFaceHeight: inch(rfHeightIn(r)),
    hubDia: inch(x),
    hubLength: inch(y - inRf),
    bolts: n,
    boltDia: inch(bd),
    boltCircle: inch(bc),
  }
}

