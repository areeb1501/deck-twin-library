export const GASKET_SPIRAL_WOUND = 0.0045 // m, compressed thickness

/** RF stud-bolt length for a flanged joint. B16.47 sizes use a rule (approx). */
export function studLength(nps: number, rating: Rating = 300): number {
  const [size, r] = resolve(nps, rating)
  const t = STUD[r][size]
  if (t !== undefined) return inch(t)
  // approx: two flanges + faces + gasket + two heavy-hex nuts + 2 x 1/4" projection, rounded up to 1/4".
  const f = flange(size, r)
  const raw = 2 * (f.thickness + f.raisedFaceHeight) + GASKET_SPIRAL_WOUND + 2 * f.boltDia + 2 * inch(0.25)
  return inch(Math.ceil(raw / 0.0254 / 0.25) * 0.25)
}

/** Blind flange thickness; B16.5 uses the same tf as the other flange types. Excludes the raised face. */
export function blindThickness(nps: number, rating: Rating = 300): number {
  return flange(nps, rating).thickness
}

// Group 1.1 rating at 38 °C, MPa.
const P38: Record<Rating, number> = { 150: 1.96, 300: 5.11, 600: 10.21, 900: 15.32, 1500: 25.53, 2500: 42.55 }

/**
 * Figure-8 spectacle blind (ASME B16.48). approx: thickness from t = d·sqrt(3P/16S), S = 138 MPa,
 * d = RF diameter, rounded up to 1/16"; disc OD fits inside the bolts; centres = bolt circle.
 */
export function spectacleBlind(
  nps: number,
  rating: Rating = 300,
): { thickness: number; od: number; webWidth: number; centres: number } {
  const [size, r] = resolve(nps, rating)
  const f = flange(size, r)
  const t = f.raisedFace * Math.sqrt((3 * P38[r]) / (16 * 138))
  const sixteenth = inch(1 / 16)
  return {
    thickness: Math.max(mm(3.2), Math.ceil(t / sixteenth) * sixteenth),
    od: f.boltCircle - f.boltDia - mm(3),
    webWidth: inch(Math.max(1.25, Math.min(4, 1 + 0.12 * size))),
    centres: f.boltCircle,
  }
}
